print("\n=== Очистка замечаний и сброс меток DoR ===")
for key in ["JS-39", "JS-40"]:
    issue = requests.get(f"{u}/rest/api/2/issue/{key}", auth=a).json()
    labels = issue.get("fields", {}).get("labels", [])
    new_labels = [l for l in labels if l != "qa-dor-failed"]
    if labels != new_labels:
        requests.put(f"{u}/rest/api/2/issue/{key}", auth=a, json={"fields": {"labels": new_labels}})
        print(f"[{key}] Метка 'qa-dor-failed' снята.")

    comments = issue.get("fields", {}).get("comment", {}).get("comments", [])
    for c in comments:
        requests.delete(f"{u}/rest/api/2/issue/{key}/comment/{c['id']}", auth=a)
        print(f"[{key}] Удален комментарий {c['id']}")

    trans = requests.get(f"{u}/rest/api/2/issue/{key}/transitions", auth=a).json().get("transitions", [])
    to_do = [t for t in trans if t.get("to", {}).get("name") in ["К выполнению", "To Do"]]
    if to_do:
        requests.post(f"{u}/rest/api/2/issue/{key}/transitions", auth=a, json={"transition": {"id": to_do[0]["id"]}})
        print(f"[{key}] Переведен в статус: К выполнению")

print("\n=== Все задачи обновлены и готовы к проверке! ===")
