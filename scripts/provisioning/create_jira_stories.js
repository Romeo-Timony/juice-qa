async function createStory(story) {
  return new Promise((resolve, reject) => {
    const postData = JSON.stringify({
      fields: {
        project: { key: projectKey },
        parent: { key: epicKey },
        issuetype: { id: '10051' }, // История
        summary: story.summary,
        description: story.description
      }
    });

    const req = https.request({
      hostname: 'romeo-timony.atlassian.net',
      path: '/rest/api/3/issue',
      method: 'POST',
      headers: {
        'Authorization': 'Basic ' + auth,
        'Content-Type': 'application/json',
        'Accept': 'application/json'
      }
    }, res => {
      let d = '';
      res.on('data', c => d += c);
      res.on('end', () => {
        if (res.statusCode >= 200 && res.statusCode < 300) {
          resolve(JSON.parse(d));
        } else {
          reject(new Error(`Status ${res.statusCode}: ${d}`));
        }
      });
    });

    req.on('error', reject);
    req.write(postData);
    req.end();
  });
}

(async () => {
  console.log(`Starting creation of ${stories.length} stories linked to Epic ${epicKey}...`);
  for (let i = 0; i < stories.length; i++) {
    const s = stories[i];
    try {
      const res = await createStory(s);
      console.log(`[${i + 1}/${stories.length}] Created Story ${res.key}: ${s.summary}`);
    } catch (err) {
      console.error(`Failed to create story "${s.summary}":`, err.message);
    }
  }
  console.log('Finished creating all stories!');
})();
