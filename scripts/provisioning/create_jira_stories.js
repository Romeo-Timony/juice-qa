function h2(text) {
  return {
    type: 'heading',
    attrs: { level: 2 },
    content: [{ type: 'text', text }]
  };
}

function h3(text) {
  return {
    type: 'heading',
    attrs: { level: 3 },
    content: [{ type: 'text', text }]
  };
}

function p(text, boldPrefix) {
  const content = [];
  if (boldPrefix) {
    content.push({ type: 'text', text: boldPrefix, marks: [{ type: 'strong' }] });
  }
  content.push({ type: 'text', text });
  return {
    type: 'paragraph',
    content
  };
}

function bulletList(items) {
  return {
    type: 'bulletList',
    content: items.map(item => ({
      type: 'listItem',
      content: [
        {
          type: 'paragraph',
          content: typeof item === 'string' 
            ? [{ type: 'text', text: item }]
            : item
        }
      ]
    }))
  };
}

function codeBlock(text) {
  return {
    type: 'codeBlock',
    attrs: { language: 'gherkin' },
    content: [{ type: 'text', text }]
  };
}

