async function createIssue(fields) {
  return await apiRequest('/rest/api/3/issue', 'POST', { fields });
}

async function linkIssues(inwardKey, outwardKey, typeName = 'Relates') {
  return await apiRequest('/rest/api/3/issueLink', 'POST', {
    type: { name: typeName },
    inwardIssue: { key: inwardKey },
    outwardIssue: { key: outwardKey }
  });
}

