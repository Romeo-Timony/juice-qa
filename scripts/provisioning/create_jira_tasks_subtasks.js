function h2(text) {
  return {
    type: 'heading',
    attrs: { level: 2 },
    content: [{ type: 'text', text }]
  };
}

function h3(text) {
  return {
    type: 'heading',
    attrs: { level: 3 },
    content: [{ type: 'text', text }]
  };
}

function p(text, boldPrefix) {
  const content = [];
  if (boldPrefix) {
    content.push({ type: 'text', text: boldPrefix, marks: [{ type: 'strong' }] });
  }
  content.push({ type: 'text', text });
  return {
    type: 'paragraph',
    content
  };
}

function bulletList(items) {
  return {
    type: 'bulletList',
    content: items.map(item => ({
      type: 'listItem',
      content: [
        {
          type: 'paragraph',
          content: typeof item === 'string'
            ? [{ type: 'text', text: item }]
            : item
        }
      ]
    }))
  };
}

function codeBlock(text, lang = 'javascript') {
  return {
    type: 'codeBlock',
    attrs: { language: lang },
    content: [{ type: 'text', text }]
  };
}

function apiRequest(path, method, data) {
  return new Promise((resolve, reject) => {
    const postData = data ? JSON.stringify(data) : null;
    const req = https.request({
      hostname: 'romeo-timony.atlassian.net',
      path,
      method,
      headers: {
        'Authorization': 'Basic ' + auth,
        'Content-Type': 'application/json',
        'Accept': 'application/json'
      }
    }, res => {
      let d = '';
      res.on('data', c => d += c);
      res.on('end', () => {
        if (res.statusCode >= 200 && res.statusCode < 300) {
          resolve(d ? JSON.parse(d) : {});
        } else {
          reject(new Error(`HTTP ${res.statusCode}: ${d}`));
        }
      });
    });
    req.on('error', reject);
    if (postData) req.write(postData);
    req.end();
  });
}

